#!/usr/bin/env python3
# Text in game is real geometry: this turns tools/fontatlas.png into rectangles per glyph
# (Scripts/fontglyphs.lua) and writes the colour palette its emissive material samples
# (palette.png: 6 levels per channel, 36x6 cells of 8 px).
#   python3 tools/make_fontglyphs.py
import os, re
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
LOADER = os.path.join(HERE, '..', 'loader', 'ETBRLoader')
CELL, BLOCK = 64, 2  # sample every 2 px of the 64 px cell
im = Image.open(os.path.join(HERE, 'fontatlas.png')).convert('L')
widths = [int(x) for x in re.search(r'return \{([^}]*)\}', open(os.path.join(LOADER, 'Scripts', 'fontwidths.lua')).read()).group(1).split(',')]

out, total = [], 0
for code in range(96):
    col, row = code % 16, code // 16
    w = widths[code]
    left = col * CELL + (CELL - w) // 2
    top = row * CELL
    grid = []
    for gy in range(CELL // BLOCK):
        line = []
        for gx in range(w // BLOCK + 1):
            box = (left + gx * BLOCK, top + gy * BLOCK, left + (gx + 1) * BLOCK, top + (gy + 1) * BLOCK)
            px = im.crop(box).getdata()
            line.append(sum(px) / len(px) > 110)
        grid.append(line)
    # runs per row, then merge identical runs on consecutive rows
    open_rects, rects = {}, []
    for gy, line in enumerate(grid + [[False] * (w // BLOCK + 1)]):
        runs, gx = set(), 0
        while gx < len(line):
            if line[gx]:
                s = gx
                while gx < len(line) and line[gx]: gx += 1
                runs.add((s, gx))
            else:
                gx += 1
        for k in [k for k in open_rects if k not in runs]:
            rects.append((k[0] * BLOCK, open_rects.pop(k) * BLOCK, k[1] * BLOCK, gy * BLOCK))
        for k in runs:
            open_rects.setdefault(k, gy)
    total += len(rects)
    out.append('{' + ','.join(str(v) for r in rects for v in r) + '}')

with open(os.path.join(LOADER, 'Scripts', 'fontglyphs.lua'), 'w') as f:
    f.write('-- generated by tools/make_fontglyphs.py: x0,y0,x1,y1 rectangles (px of a 64 px cell) for ASCII 32..127\n')
    f.write('return {\n' + ',\n'.join(out) + '\n}\n')

pal = Image.new('RGB', (36 * 8, 6 * 8))
for r in range(6):
    for g in range(6):
        for b in range(6):
            pal.paste((r * 51, g * 51, b * 51), ((r * 6 + g) * 8, b * 8, (r * 6 + g + 1) * 8, (b + 1) * 8))
pal.save(os.path.join(LOADER, 'palette.png'))
print('glyph rects:', total, 'avg per glyph:', total // 95)
